/**
 * Writes the homepage's top-bar menus (Product, Solutions, Resources) into
 * every static page, from the same data the React nav reads:
 *   web/src/data/product-pages.ts  Product mega-menu
 *   web/src/data/nav-links.ts      Solutions and Resources dropdowns
 *
 * Run after changing either file:
 *   node --experimental-strip-types scripts/sync-static-nav.mjs
 *
 * Idempotent. It replaces the <nav class="nav-links"> and <nav class="menu">
 * blocks and the panels between the nav-menus markers, and leaves the rest of
 * each page alone. Pages without a nav-links block (the focused waitlist bar)
 * are skipped.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { PRODUCT_PAGES, GROUPS, GROUP_BLURB, productHref } = await import(join(root, 'web/src/data/product-pages.ts'))
const { NAV_LINKS } = await import(join(root, 'web/src/data/nav-links.ts'))

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const CARET = '<svg width="12" height="12" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true"><path d="M216.49,104.49l-80,80a12,12,0,0,1-17,0l-80-80a12,12,0,0,1,17-17L128,159l71.51-71.52a12,12,0,0,1,17,17Z"/></svg>'
const STATUS = { roadmap: 'Roadmap', concept: 'Concept' }
const tag = s => (STATUS[s] ? ` <span class="status-tag" data-status="${s}">${STATUS[s]}</span>` : '')

/** Page path as served with clean URLs: about.html -> /about, blog/index.html -> /blog. */
const urlOf = file => '/' + file.replace(/\\/g, '/').replace(/(^|\/)index\.html$/, '').replace(/\.html$/, '')

function render(path) {
  const cur = href => (href === path ? ' aria-current="page"' : '')
  const menus = { product: PRODUCT_PAGES.map(p => productHref(p.slug)), ...Object.fromEntries(Object.entries(NAV_LINKS).map(([k, v]) => [k, v.map(l => l.href)])) }
  const trigger = (m, label) =>
    `<button type="button" class="nav-link" data-menu="${m}" aria-expanded="false" aria-controls="menu-${m}"${menus[m].includes(path) ? ' data-current' : ''}>${label} ${CARET}</button>`

  const links = `<nav class="nav-links" aria-label="Site">
      ${trigger('product', 'Product')}
      ${trigger('solutions', 'Solutions')}
      ${trigger('resources', 'Resources')}
    </nav>`

  const groups = GROUPS.map(g => {
    const items = PRODUCT_PAGES.filter(p => p.group === g).map(p => `
          <li><a href="${productHref(p.slug)}"${cur(productHref(p.slug))}><span class="mm-item-label">${esc(p.label)}${tag(p.status)}</span><span class="mm-item-detail">${esc(p.detail)}</span></a></li>`).join('')
    return `
      <div class="mm-group"${g === 'Next' ? ' data-next' : ''}>
        <div class="mm-group-title">${g}</div>
        <p class="mm-group-blurb">${esc(GROUP_BLURB[g])}</p>
        <ul>${items}
        </ul>
      </div>`
  }).join('')
  const dd = m => `
  <div id="menu-${m}" class="dd" data-menu="${m}">
    <ul>${NAV_LINKS[m].map(l => `<li><a href="${l.href}"${cur(l.href)}>${esc(l.label)}</a></li>`).join('')}</ul>
  </div>`
  const panels = `<!-- nav-menus: generated by scripts/sync-static-nav.mjs -->
  <div id="menu-product" class="mm" data-menu="product">
    <div class="mm-inner">${groups}
    </div>
  </div>${dd('solutions')}${dd('resources')}
  <!-- /nav-menus -->
`

  const mobile = [
    ['/product', 'Product'],
    ...NAV_LINKS.solutions.map(l => [l.href, l.label]),
    ...NAV_LINKS.resources.map(l => [l.href, l.label]),
    ['/waitlist', 'Request access'],
  ]
  const menu = `<nav class="menu" id="mobile-menu" aria-label="Mobile">
${mobile.map(([href, label]) => `  <a href="${href}"${cur(href)}>${esc(label)}</a>`).join('\n')}
</nav>`
  return { links, panels, menu }
}

async function* htmlFiles(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (dir === root && !['blog', 'integrations'].includes(e.name)) continue
      yield* htmlFiles(join(dir, e.name))
    } else if (e.name.endsWith('.html')) yield join(dir, e.name)
  }
}

let n = 0
for await (const file of htmlFiles(root)) {
  let s = await readFile(file, 'utf8')
  if (!s.includes('<nav class="nav-links"')) continue
  const rel = relative(root, file)
  const { links, panels, menu } = render(rel === '404.html' ? '' : urlOf(rel))
  s = s.replace(/<nav class="nav-links"[\s\S]*?<\/nav>/, links)
  s = s.replace(/<nav class="menu"[\s\S]*?<\/nav>/, menu)
  s = s.replace(/ *<!-- nav-menus[\s\S]*?<!-- \/nav-menus -->\n/, '')
  s = s.replace(/(<header class="nav"[\s\S]*?)(<\/header>)/, `$1${panels}$2`)
  s = s.replace('<button class="nav-burger" aria-label="Menu" aria-expanded="false">', '<button class="nav-burger" aria-label="Menu" aria-expanded="false" aria-controls="mobile-menu">')
  await writeFile(file, s)
  n++
}
console.log(`[sync-static-nav] ${n} pages`)
